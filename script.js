let currentLang = 'en';

function setLanguage(lang) {
  currentLang = lang;
  const t = translations[lang];

  document.title = t.title;
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.content = t.metaDesc;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) {
      el.textContent = t[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) {
      el.placeholder = t[key];
    }
  });

  document.documentElement.lang = lang;
}

document.addEventListener('DOMContentLoaded', () => {
  const langToggleBtn = document.getElementById('langToggle');
  const mobileMenuBtn = document.getElementById('mobileMenuBtn');
  const navLinks = document.querySelector('.nav-links');

  if (langToggleBtn) {
    langToggleBtn.addEventListener('click', () => {
      const newLang = currentLang === 'en' ? 'so' : 'en';
      setLanguage(newLang);
      navLinks.classList.remove('active');
    });
  }

  if (mobileMenuBtn) {
    mobileMenuBtn.addEventListener('click', () => {
      navLinks.classList.toggle('active');
    });
  }

  navLinks.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', () => {
      navLinks.classList.remove('active');
    });
  });

  const bookingForm = document.getElementById('bookingForm');
  const formMessage = document.getElementById('formMessage');
  const whatsappBtn = document.getElementById('whatsappBtn');

  if (bookingForm) {
    bookingForm.addEventListener('submit', (e) => {
      e.preventDefault();
      const t = translations[currentLang];

      const fullName = document.getElementById('fullName').value.trim();
      const phone = document.getElementById('phone').value.trim();
      const service = document.getElementById('service').value;
      const date = document.getElementById('date').value.trim();
      const time = document.getElementById('time').value;

      formMessage.className = 'form-message';

      if (!fullName || !phone || !service || !date || !time) {
        formMessage.textContent = t.msgError;
        formMessage.classList.add('error');
        return;
      }

      formMessage.textContent = t.msgSuccess;
      formMessage.classList.add('success');
      bookingForm.reset();
    });
  }

  if (whatsappBtn) {
    whatsappBtn.addEventListener('click', () => {
      const t = translations[currentLang];
      const fullName = document.getElementById('fullName').value.trim();
      const phone = document.getElementById('phone').value.trim();
      const service = document.getElementById('service').value;
      const date = document.getElementById('date').value.trim();
      const time = document.getElementById('time').value;

      formMessage.className = 'form-message';

      if (!fullName || !phone || !service || !date || !time) {
        formMessage.textContent = t.msgError;
        formMessage.classList.add('error');
        return;
      }

      const text = `Hello Oral Dental Care, I would like to book an appointment.\nName: ${fullName}\nPhone: ${phone}\nService: ${service}\nDate: ${date}\nTime: ${time}`;
      const whatsappUrl = `https://wa.me/252617000000?text=${encodeURIComponent(text)}`;
      window.open(whatsappUrl, '_blank');
    });
  }
});